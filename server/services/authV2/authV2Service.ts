/**
 * AuthV2Service — server-side authentication core for the NEXA v2 contract.
 *
 * Implements the contract the APK/web client already expects:
 *   POST /v2/pair/redeem      — pair a device with a one-time pairing code
 *   POST /v2/session/challenge — request a login challenge for a paired device
 *   POST /v2/session/redeem    — redeem challenge response for a session token
 *   POST /v2/auth/logout       — revoke the current session
 *
 * Security properties enforced HERE (server-side, never trusting the client):
 *   - Pairing codes are single-use, expire, and are compared in constant time.
 *   - Challenges are single-use, expire, and are bound to the requesting device.
 *   - The challenge response is HMAC-SHA256(nonce, deviceSecret): the server
 *     verifies device possession without the secret ever leaving the client.
 *   - Session tokens are random 256-bit values with expiry; the server keeps
 *     only their SHA-256 hash, so a store leak does not leak usable tokens.
 *   - Sessions are revocable (logout / device revoke) and expire absolutely.
 *   - Roles/permissions are assigned at pairing time by the server, never by
 *     the client. Authorization is deny-by-default.
 *   - PIN, biometrics, confirmations, idempotency keys or headers sent by the
 *     client are NEVER a substitute for this authorization.
 *
 * Persistence: this core is storage-agnostic (AuthV2Store interface). The
 * in-memory implementation is correct for tests and for validating the
 * contract; the durable DB-backed store (drizzle, expand-only migration) is
 * a separate, explicitly pending convergence item — sessions survive restart
 * only once it lands. Pairing durability has the same caveat.
 */

import { randomBytes, createHash, verify as cryptoVerify } from "crypto";

export type AuthV2Role = "admin" | "operator" | "reader";

export interface AuthV2Device {
  deviceId: string; // generated by the client, verified unique at pairing
  publicKeySpkiB64: string; // ECDSA P-256 SPKI, base64 — private key never leaves the device
  roles: AuthV2Role[];
  pairedAt: number;
  revokedAt: number | null;
  label?: string;
  platform?: string;
}

export interface AuthV2Session {
  tokenHash: string;
  deviceId: string;
  roles: AuthV2Role[];
  createdAt: number;
  expiresAt: number;
  revokedAt: number | null;
}

export interface AuthV2Store {
  saveDevice(device: AuthV2Device): void;
  getDevice(deviceId: string): AuthV2Device | undefined;
  revokeDevice(deviceId: string, at: number): void;
  savePairingCode(codeHash: string, roles: AuthV2Role[], expiresAt: number): void;
  consumePairingCode(codeHash: string): { roles: AuthV2Role[]; expiresAt: number } | null;
  saveChallenge(nonceHash: string, deviceId: string, expiresAt: number): void;
  consumeChallenge(nonceHash: string): { deviceId: string; expiresAt: number } | null;
  saveSession(session: AuthV2Session): void;
  getSession(tokenHash: string): AuthV2Session | undefined;
  revokeSession(tokenHash: string, at: number): void;
}

export class InMemoryAuthV2Store implements AuthV2Store {
  private devices = new Map<string, AuthV2Device>();
  private pairingCodes = new Map<string, { roles: AuthV2Role[]; expiresAt: number }>();
  private challenges = new Map<string, { deviceId: string; expiresAt: number }>();
  private sessions = new Map<string, AuthV2Session>();

  saveDevice(device: AuthV2Device): void {
    this.devices.set(device.deviceId, device);
  }
  getDevice(deviceId: string): AuthV2Device | undefined {
    return this.devices.get(deviceId);
  }
  revokeDevice(deviceId: string, at: number): void {
    const d = this.devices.get(deviceId);
    if (d) d.revokedAt = at;
    // Revoking a device revokes all its sessions.
    for (const s of this.sessions.values()) {
      if (s.deviceId === deviceId && !s.revokedAt) s.revokedAt = at;
    }
  }
  savePairingCode(codeHash: string, roles: AuthV2Role[], expiresAt: number): void {
    this.pairingCodes.set(codeHash, { roles, expiresAt });
  }
  consumePairingCode(codeHash: string): { roles: AuthV2Role[]; expiresAt: number } | null {
    const entry = this.pairingCodes.get(codeHash);
    if (!entry) return null;
    this.pairingCodes.delete(codeHash); // single-use
    return entry;
  }
  saveChallenge(nonceHash: string, deviceId: string, expiresAt: number): void {
    this.challenges.set(nonceHash, { deviceId, expiresAt });
  }
  consumeChallenge(nonceHash: string): { deviceId: string; expiresAt: number } | null {
    const entry = this.challenges.get(nonceHash);
    if (!entry) return null;
    this.challenges.delete(nonceHash); // single-use, replay prevention
    return entry;
  }
  saveSession(session: AuthV2Session): void {
    this.sessions.set(session.tokenHash, session);
  }
  getSession(tokenHash: string): AuthV2Session | undefined {
    return this.sessions.get(tokenHash);
  }
  revokeSession(tokenHash: string, at: number): void {
    const s = this.sessions.get(tokenHash);
    if (s) s.revokedAt = at;
  }
}

function sha256Hex(input: string): string {
  return createHash("sha256").update(input, "utf8").digest("hex");
}

/**
 * Verify an ECDSA P-256/SHA-256 signature over the UTF-8 bytes of the nonce.
 * WebCrypto produces IEEE-P1363 signatures; we ask node for that encoding.
 * Never throws: malformed keys/signatures are simply invalid.
 */
function verifyDeviceSignature(publicKeySpkiB64: string, nonce: string, signatureB64: string): boolean {
  try {
    const key = Buffer.from(publicKeySpkiB64, "base64");
    const signature = Buffer.from(signatureB64, "base64");
    return cryptoVerify(
      "sha256",
      Buffer.from(nonce, "utf8"),
      { key, format: "der", type: "spki", dsaEncoding: "ieee-p1363" },
      signature
    );
  } catch {
    return false;
  }
}

export const AUTHV2_PAIRING_CODE_TTL_MS = 10 * 60 * 1000; // 10 minutes
export const AUTHV2_CHALLENGE_TTL_MS = 5 * 60 * 1000; // 5 minutes
export const AUTHV2_SESSION_TTL_MS = 12 * 60 * 60 * 1000; // 12 hours

export class AuthV2Service {
  constructor(
    private store: AuthV2Store,
    private now: () => number = () => Date.now()
  ) {}

  /**
   * Issue a one-time pairing code. Only callable from an already-authenticated
   * admin session (enforced by the route layer). Roles are assigned HERE.
   */
  issuePairingCode(roles: AuthV2Role[]): { code: string; expiresAt: number } {
    const code = randomBytes(6).toString("hex"); // 12 hex chars, human-copyable
    const expiresAt = this.now() + AUTHV2_PAIRING_CODE_TTL_MS;
    this.store.savePairingCode(sha256Hex(code), roles, expiresAt);
    return { code, expiresAt };
  }

  /**
   * Redeem a pairing code: registers a device with server-assigned roles.
   * Contract: the client generates its own deviceId and ECDSA keypair; the
   * private key never leaves the device. A deviceId already registered cannot
   * be re-paired (no silent credential overwrite).
   */
  redeemPairing(code: string, deviceId: string, publicKeySpkiB64: string, label?: string, platform?: string): { roles: AuthV2Role[] } | null {
    if (!deviceId || deviceId.length < 8 || deviceId.length > 128) return null;
    if (!publicKeySpkiB64 || publicKeySpkiB64.length > 512) return null;
    const entry = this.store.consumePairingCode(sha256Hex(code)); // single-use even if wrong/expired
    if (!entry) return null;
    if (entry.expiresAt < this.now()) return null;
    if (this.store.getDevice(deviceId)) return null;
    const device: AuthV2Device = {
      deviceId,
      publicKeySpkiB64,
      roles: entry.roles,
      pairedAt: this.now(),
      revokedAt: null,
      label,
      platform,
    };
    this.store.saveDevice(device);
    return { roles: entry.roles };
  }

  /** Issue a login challenge for a paired, non-revoked device. */
  createChallenge(deviceId: string): { nonce: string; expiresAt: number } | null {
    const device = this.store.getDevice(deviceId);
    if (!device || device.revokedAt) return null;
    const nonce = randomBytes(32).toString("hex");
    const expiresAt = this.now() + AUTHV2_CHALLENGE_TTL_MS;
    this.store.saveChallenge(sha256Hex(nonce), deviceId, expiresAt);
    return { nonce, expiresAt };
  }

  /**
   * Redeem a challenge response for a session token.
   * The response must be HMAC-SHA256(deviceSecret, nonce), hex-encoded.
   * The challenge is consumed even on failure: no oracle, no replay.
   */
  redeemChallenge(deviceId: string, nonce: string, signatureB64: string): { token: string; expiresAt: number; roles: AuthV2Role[] } | null {
    const challenge = this.store.consumeChallenge(sha256Hex(nonce));
    if (!challenge) return null;
    if (challenge.expiresAt < this.now()) return null;
    if (challenge.deviceId !== deviceId) return null;
    const device = this.store.getDevice(deviceId);
    if (!device || device.revokedAt) return null;
    if (!verifyDeviceSignature(device.publicKeySpkiB64, nonce, signatureB64)) return null;

    const token = randomBytes(32).toString("hex");
    const expiresAt = this.now() + AUTHV2_SESSION_TTL_MS;
    this.store.saveSession({
      tokenHash: sha256Hex(token),
      deviceId,
      roles: device.roles,
      createdAt: this.now(),
      expiresAt,
      revokedAt: null,
    });
    return { token, expiresAt, roles: device.roles };
  }

  /** Validate a bearer token. Returns null when invalid/expired/revoked. */
  validateToken(token: string): { deviceId: string; roles: AuthV2Role[] } | null {
    const session = this.store.getSession(sha256Hex(token));
    if (!session) return null;
    if (session.revokedAt) return null;
    if (session.expiresAt < this.now()) return null;
    const device = this.store.getDevice(session.deviceId);
    if (!device || device.revokedAt) return null;
    return { deviceId: session.deviceId, roles: session.roles };
  }

  /** Authorization check: deny by default. admin implies every permission. */
  hasPermission(roles: AuthV2Role[], permission: string): boolean {
    if (!permission) return false;
    return roles.includes("admin") || roles.includes(permission as AuthV2Role);
  }

  revokeToken(token: string): void {
    this.store.revokeSession(sha256Hex(token), this.now());
  }

  revokeDevice(deviceId: string): void {
    this.store.revokeDevice(deviceId, this.now());
  }
}

/** Shared singleton — store is in-memory until the durable DB store lands. */
export const authV2Service = new AuthV2Service(new InMemoryAuthV2Store());
